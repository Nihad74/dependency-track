CREATE TABLE IF NOT EXISTS "ASSESSMENT_SYNC_OUTBOX" (
  "ID" BIGINT GENERATED ALWAYS AS IDENTITY
, "SCHEMA_VERSION" INT NOT NULL DEFAULT 1 -- squawk-ignore prefer-bigint-over-int
, "TRANSACTION_ID" XID8 NOT NULL DEFAULT pg_current_xact_id()
, "SCOPE_KEY" TEXT NOT NULL
, "SCOPE" TEXT NOT NULL
, "PROJECT_UUID" UUID NOT NULL
, "COMPONENT_UUID" UUID
, "VULNERABILITY_UUID" UUID
, "REASON" TEXT NOT NULL
, "LOOKUP_KEYS" JSONB NOT NULL DEFAULT '[]'::jsonb
, "FANOUT_CURSOR" UUID
, "CREATED_AT" TIMESTAMPTZ(3) NOT NULL DEFAULT now()
, "NEXT_DISPATCH_AT" TIMESTAMPTZ(3) NOT NULL DEFAULT now()
, "DISPATCH_ATTEMPTS" INT NOT NULL DEFAULT 0 -- squawk-ignore prefer-bigint-over-int
, "LAST_ERROR_CODE" TEXT
, CONSTRAINT "ASSESSMENT_SYNC_OUTBOX_PK" PRIMARY KEY ("ID")
, CONSTRAINT "ASSESSMENT_SYNC_OUTBOX_TRANSACTION_SCOPE_UQ" UNIQUE ("TRANSACTION_ID", "SCOPE_KEY")
, CONSTRAINT "ASSESSMENT_SYNC_OUTBOX_SCHEMA_VERSION_CHECK" CHECK ("SCHEMA_VERSION" = 1)
, CONSTRAINT "ASSESSMENT_SYNC_OUTBOX_SCOPE_CHECK" CHECK ("SCOPE" IN ('FINDING', 'PROJECT'))
, CONSTRAINT "ASSESSMENT_SYNC_OUTBOX_SCOPE_SHAPE_CHECK" CHECK (
    ("SCOPE" = 'PROJECT' AND "COMPONENT_UUID" IS NULL AND "VULNERABILITY_UUID" IS NULL)
    OR ("SCOPE" = 'FINDING' AND "COMPONENT_UUID" IS NOT NULL AND "VULNERABILITY_UUID" IS NOT NULL)
  )
);

-- squawk-ignore require-concurrent-index-creation
CREATE INDEX IF NOT EXISTS "ASSESSMENT_SYNC_OUTBOX_NEXT_DISPATCH_IDX"
    ON "ASSESSMENT_SYNC_OUTBOX" ("NEXT_DISPATCH_AT", "ID");

CREATE TABLE IF NOT EXISTS "ASSESSMENT_SYNC_WORK" (
  "TARGET_UUID" UUID NOT NULL
, "REQUESTED_REVISION" BIGINT NOT NULL DEFAULT 0
, "COMPLETED_REVISION" BIGINT NOT NULL DEFAULT 0
, "FULL_REVISION" BIGINT NOT NULL DEFAULT 0
, "ACTIVE_REVISION" BIGINT
, "ACTIVE_FULL" BOOLEAN NOT NULL DEFAULT false
, "CURSOR_COMPONENT_ID" BIGINT
, "CURSOR_VULNERABILITY_ID" BIGINT
, "REFRESH_REQUESTED" BIGINT NOT NULL DEFAULT 0
, "REFRESH_COMPLETED" BIGINT NOT NULL DEFAULT 0
, "NEXT_DISPATCH_AT" TIMESTAMPTZ(3) NOT NULL DEFAULT now()
, "LAST_SUCCESS_AT" TIMESTAMPTZ(3)
, "LAST_ERROR_CODE" TEXT
, "LAST_RESULT" JSONB NOT NULL DEFAULT '{}'::jsonb
, CONSTRAINT "ASSESSMENT_SYNC_WORK_PK" PRIMARY KEY ("TARGET_UUID")
, CONSTRAINT "ASSESSMENT_SYNC_WORK_COMPLETED_REVISION_CHECK" CHECK ("COMPLETED_REVISION" <= "REQUESTED_REVISION")
, CONSTRAINT "ASSESSMENT_SYNC_WORK_FULL_REVISION_CHECK" CHECK ("FULL_REVISION" <= "REQUESTED_REVISION")
, CONSTRAINT "ASSESSMENT_SYNC_WORK_REFRESH_COMPLETED_CHECK" CHECK ("REFRESH_COMPLETED" <= "REFRESH_REQUESTED")
, CONSTRAINT "ASSESSMENT_SYNC_WORK_ACTIVE_REVISION_CHECK" CHECK ("ACTIVE_REVISION" <= "REQUESTED_REVISION")
);

-- squawk-ignore require-concurrent-index-creation
CREATE INDEX IF NOT EXISTS "ASSESSMENT_SYNC_WORK_NEXT_DISPATCH_IDX"
    ON "ASSESSMENT_SYNC_WORK" ("NEXT_DISPATCH_AT", "TARGET_UUID")
 WHERE "COMPLETED_REVISION" < "REQUESTED_REVISION"
    OR "REFRESH_COMPLETED" < "REFRESH_REQUESTED";

